// Explicit `.ts` extensions: `scripts/generate-avatar-motion-table.ts` runs this
// module under plain Node, which does not resolve extensionless specifiers.
import { AVATAR_MOTIONS, type AvatarMotion } from "../avatarMotion.ts";
import { differsFromRest, holdStill, num, sampleLayer, simplify } from "./avatarKeyframes.ts";
import { avatarStateTiming } from "./avatarStates.ts";
import { AVATAR_BODY_PIVOT_Y, REST_POSE, type AvatarPose } from "./pose.ts";

/**
 * The table the Android avatar plays: the web CSS sampling in two layers, body (translate,
 * rotate, scale about the box centre, so `pivotedTranslate` carries the (50, 52) pivot) and eyes
 * (gaze, widen, open, happy). A layer has a `lead` track and, for loops, a steady `loop` track.
 */

interface TableLayer {
  readonly name: "body" | "eyes";
  readonly period: "body" | "eyes";
  readonly channels: (pose: AvatarPose) => readonly number[];
  readonly tolerance: readonly number[];
}

const DEGREES = Math.PI / 180;

/**
 * Translate that makes a rotate and scale about the box centre land where the
 * same pose about the pivot (50, 52) does, in the same percent units.
 */
export function pivotedTranslate(pose: AvatarPose): readonly [number, number] {
  const offset = AVATAR_BODY_PIVOT_Y - 50;
  const angle = pose.bodyRotate * DEGREES;
  return [
    pose.bodyX + offset * pose.bodyScaleY * Math.sin(angle),
    pose.bodyY + offset - offset * pose.bodyScaleY * Math.cos(angle),
  ];
}

const TABLE_LAYERS: readonly TableLayer[] = [
  {
    name: "body",
    period: "body",
    channels: (pose) => [
      ...pivotedTranslate(pose),
      pose.bodyRotate,
      pose.bodyScaleX,
      pose.bodyScaleY,
    ],
    tolerance: [0.04, 0.04, 0.08, 0.002, 0.002],
  },
  {
    name: "eyes",
    period: "eyes",
    channels: (pose) => [pose.gazeX, pose.gazeY, pose.eyeWiden, pose.eyeOpen, pose.happy],
    tolerance: [0.04, 0.04, 0.005, 0.015, 0.015],
  },
];

export const AVATAR_TABLE_STATES = AVATAR_MOTIONS.filter(
  (motion): motion is Exclude<AvatarMotion, "idle"> => motion !== "idle",
);

interface TrackData {
  readonly seconds: number;
  readonly times: readonly number[];
  readonly values: readonly (readonly number[])[];
}

function restRow(layer: TableLayer): readonly number[] {
  return layer.channels(REST_POSE);
}

function track(
  layer: TableLayer,
  samples: readonly (readonly number[])[],
  seconds: number,
): TrackData | null {
  if (!differsFromRest(samples, restRow(layer))) return null;
  const held = holdStill(samples, layer.tolerance);
  const kept = simplify(held, layer.tolerance);
  const last = held.length - 1;
  return {
    seconds,
    times: kept.map((index) => Number(num(index / last))),
    values: layer.tolerance.map((_, channel) =>
      kept.map((index) => Number(num(held[index]![channel]!))),
    ),
  };
}

function layerTracks(state: Exclude<AvatarMotion, "idle">, layer: TableLayer) {
  const timing = avatarStateTiming(state);
  if (!timing.loop) {
    return {
      lead: track(layer, sampleLayer(state, layer, 0, timing.seconds), timing.seconds),
      loop: null,
    };
  }
  const period = layer.period === "body" ? timing.bodySeconds : timing.eyeSeconds;
  const intro = sampleLayer(state, layer, 0, timing.introSeconds);
  const steady = sampleLayer(state, layer, timing.introSeconds, period);
  const both = [...intro, ...steady];
  if (!differsFromRest(both, restRow(layer))) return { lead: null, loop: null };
  return {
    lead: track(layer, intro, timing.introSeconds),
    loop: track(layer, steady, period),
  };
}

function array(values: readonly number[]): string {
  return `[${values.join(", ")}]`;
}

function trackSource(value: TrackData | null, indent: string): string {
  if (value === null) return "null";
  const rows = value.values.map((row) => `${indent}    ${array(row)},`).join("\n");
  return (
    `{\n${indent}  seconds: ${num(value.seconds)},\n` +
    `${indent}  times: ${array(value.times)},\n` +
    `${indent}  values: [\n${rows}\n${indent}  ],\n${indent}}`
  );
}

/** The whole generated module (`avatarMotionTable.generated.ts`). */
export function avatarMotionTableSource(): string {
  const states = AVATAR_TABLE_STATES.map((state) => {
    const timing = avatarStateTiming(state);
    const layers = TABLE_LAYERS.map((layer) => {
      const tracks = layerTracks(state, layer);
      return (
        `    ${layer.name}: {\n      lead: ${trackSource(tracks.lead, "      ")},\n` +
        `      loop: ${trackSource(tracks.loop, "      ")},\n    },`
      );
    }).join("\n");
    return `  ${state}: {\n    loop: ${timing.loop},\n${layers}\n  },`;
  }).join("\n");
  return [
    "// GENERATED by apps/web/scripts/generate-avatar-motion-table.ts from",
    "// apps/web/src/features/personal/avatarRemotion/avatarStates.ts.",
    "// Do not edit by hand: change the motion, then run",
    "//   node apps/web/scripts/generate-avatar-motion-table.ts",
    "// (avatarMotionTable.test.ts fails while this file is stale).",
    "",
    "export type AvatarTableState = " +
      AVATAR_TABLE_STATES.map((state) => `"${state}"`).join(" | ") +
      ";",
    "",
    "/** Keyframes of one layer: `values[channel][keyframe]` at `times[keyframe]` (0 to 1 of `seconds`). */",
    "export interface AvatarTrack {",
    "  readonly seconds: number;",
    "  readonly times: readonly number[];",
    "  readonly values: readonly (readonly number[])[];",
    "}",
    "",
    "/** `lead` is a loop's spring-in or a one-shot's whole motion; `loop` the steady state. */",
    "export interface AvatarLayerTracks {",
    "  readonly lead: AvatarTrack | null;",
    "  readonly loop: AvatarTrack | null;",
    "}",
    "",
    "export interface AvatarStateTracks {",
    "  readonly loop: boolean;",
    "  /** translateX, translateY (percent of the box), rotate (degrees), scaleX, scaleY. */",
    "  readonly body: AvatarLayerTracks;",
    "  /** gazeX, gazeY (percent of the box), widen, open, happy. */",
    "  readonly eyes: AvatarLayerTracks;",
    "}",
    "",
    "export const AVATAR_MOTION_TABLE: Readonly<Record<AvatarTableState, AvatarStateTracks>> = {",
    states,
    "};",
    "",
  ].join("\n");
}
